export const KAMUS: Record<Bahasa, Kamus> = { id, en };
export const kamus = (b: Bahasa) => KAMUS[b];
export type { Kamus };

export function pesanGalat(b: Bahasa, kode: KodeGalat | 'setuju' | 'sibuk' | 'gagal', isi: Record<string, string | number> = {}, tgl?: (s: string) => string) {
  const g = KAMUS[b].galat;
  switch (kode) {
    case 'terlaluCepat': return g.terlaluCepat(Number(isi.hari ?? 0));
    case 'terlaluJauh': return g.terlaluJauh(Number(isi.hari ?? 365));
    case 'minMalam': return g.minMalam(Number(isi.n ?? 1));
    case 'jumlahKamar': return g.jumlahKamar(Number(isi.n ?? 1));
    case 'kapasitas': return g.kapasitas(Number(isi.n ?? 1));
    case 'penuh': return g.penuh(tgl ? tgl(String(isi.malam ?? '')) : String(isi.malam ?? ''));
    default: return g[kode];
  }
}
